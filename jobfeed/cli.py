"""jobfeed CLI (typer + rich): init, fetch, digest, apply, skip, status, export, ui."""
from __future__ import annotations

import csv
import logging
import re
import sys
from datetime import date
from pathlib import Path
from typing import Optional

import typer
from rich.console import Console
from rich.table import Table

from . import db, report, service
from .config import ROOT, get_config

app = typer.Typer(add_completion=False, help="jobfeed — a profession-agnostic job tracker")
console = Console()


def _log() -> logging.Logger:
    logger = logging.getLogger("jf")
    if not logger.handlers:
        h = logging.FileHandler("fetch.log")
        h.setFormatter(logging.Formatter("%(asctime)s %(levelname)s %(message)s"))
        logger.addHandler(h)
        logger.setLevel(logging.INFO)
    return logger


CONFIG_TEMPLATE = """\
# jobfeed config — generated by `jf init`. Tune freely; nothing here is hardcoded.
profession: "{profession}"

# What to search for. adzuna_what is your search string on Adzuna.
query:
  adzuna_what: "{what}"
  remotive_category: ""        # optional Remotive category slug (e.g. "software-dev")

# Which titles count. include = must match one; exclude = drop if any match.
# \\b is a word boundary; (?i) = case-insensitive. The base phrase also matches
# seniority variants ("Senior {profession}", "Lead {profession}", ...).
titles:
  include:
    - "(?i)\\\\b{title_re}\\\\b"
  exclude:
    - "(?i)\\\\bintern\\\\b"

locations:
  accept_remote_us: true
  states: []                   # empty = accept any US location. e.g. [CA, NY, TX]
  city_hints: {{}}              # optional: map a state to city substrings
  remote_hints: [Remote, Anywhere, Distributed, "Work from home", "US - Remote",
                 "Remote - US", "Remote (US)"]
  reject_hints: [Canada, "United Kingdom", London, Dublin, Berlin, Amsterdam,
                 Bangalore, India, Singapore, Sydney, Tokyo, Toronto, Vancouver]

compensation:
  drop_below: null             # set a number only if you mean it
  flag_below: null             # shown as a warning in the digest, not filtered
  treat_missing_as: unknown

# Additive scoring. Tune the keyword boosts/penalties to your field.
scoring:
  keyword_boosts: {{}}          # e.g. {{"(?i)\\\\bpython\\\\b": 8}}
  keyword_penalties: {{}}       # e.g. {{"(?i)clearance": -20}}
  state_boosts: {{}}            # e.g. {{CA: 10, NY: 4}}
  remote_boost: 6
  freshness:
    posted_within_3_days: 10
    posted_within_7_days: 5
    older_than_30_days: -12

digest:
  top_n: 25
  min_score: 0

fetch:
  max_requests_per_second: 8
  timeout_seconds: 10
  retries: 1

# Query-based sources need no setup beyond an Adzuna key. The ATS sources poll
# specific company boards from targets.csv — enable them only if you have one.
sources:
  adzuna: true
  remotive: true
  remoteok: true
  greenhouse: false
  ashby: false
  lever: false
"""


@app.command()
def init(
    profession: str = typer.Argument(..., help='e.g. "registered nurse"'),
    force: bool = typer.Option(False, "--force", help="overwrite an existing config.yaml"),
):
    """Generate config.yaml for a profession."""
    path = ROOT / "config.yaml"
    if path.exists() and not force:
        console.print(f"[yellow]{path} already exists[/] — pass --force to overwrite.")
        raise typer.Exit(1)
    body = CONFIG_TEMPLATE.format(
        profession=profession,
        what=profession.lower(),
        title_re=re.escape(profession).replace("\\ ", " "),
    )
    path.write_text(body)
    console.print(f"[green]wrote[/] {path} for profession: [bold]{profession}[/]")
    console.print("Next: copy .env.example to .env, add your free Adzuna key, then "
                  "`python jf.py fetch` and `python jf.py digest`.")


@app.command()
def fetch(
    targets: str = typer.Option("targets.csv", help="optional ATS boards CSV"),
    limit: Optional[int] = typer.Option(None, help="cap boards per ATS (smoke test)"),
):
    """Poll enabled sources, upsert, print per-source counts."""
    cfg = get_config()
    log = _log()
    log.info("fetch start (profession=%s)", cfg.profession)
    summary = service.run_fetch(cfg, log, targets, limit=limit)

    table = Table(title=f"jf fetch — {cfg.profession}")
    for col in ("source", "title-matches", "kept", "boards", "failed"):
        table.add_column(col, justify="right" if col != "source" else "left")
    for s in summary["sources"]:
        table.add_row(s["source"], str(s["matches"]), str(s["kept"]),
                      str(s["boards"]), str(s["failed"]))
    console.print(table)
    console.print(f"[green]stored[/]: {summary['inserted']} new, "
                  f"{summary['updated']} updated, {summary['unchanged']} unchanged")


@app.command()
def digest(all: bool = typer.Option(False, "--all", help="all new, unranked")):
    """Top-N by score (markdown), or everything new with --all."""
    cfg = get_config()
    conn = db.connect(service.DB_FILE)
    db.init_schema(conn)
    if all:
        print(report.render_digest(cfg, db.query_new_all(conn), ranked=False))
    else:
        print(report.render_digest(cfg, db.query_top(conn, cfg.digest_top_n,
                                                      cfg.digest_min_score), ranked=True))
    conn.close()


@app.command()
def apply(id: str):
    """Mark a job applied (status='applied', applied_date=today)."""
    conn = db.connect(service.DB_FILE); db.init_schema(conn)
    try:
        row = db.set_status(conn, id, "applied", applied_date=date.today().isoformat())
    except KeyError as e:
        console.print(f"[red]{e}[/]"); raise typer.Exit(1)
    console.print(f"[green]applied[/] {row['title']} — {row['company']}")
    conn.close()


@app.command()
def skip(id: str, why: str = typer.Option(None, "--why", help="reason (stored in notes)")):
    """Mark a job skipped, optionally with a reason."""
    conn = db.connect(service.DB_FILE); db.init_schema(conn)
    try:
        row = db.set_status(conn, id, "skipped", notes=why)
    except KeyError as e:
        console.print(f"[red]{e}[/]"); raise typer.Exit(1)
    console.print(f"[yellow]skipped[/] {row['title']} — {row['company']}"
                  + (f"  ({why})" if why else ""))
    conn.close()


@app.command()
def status():
    """Funnel counts + applies-per-week trend."""
    conn = db.connect(service.DB_FILE); db.init_schema(conn)
    counts = db.status_counts(conn)
    table = Table(title="funnel")
    table.add_column("status"); table.add_column("count", justify="right")
    for st in ("new", "interested", "applied", "skipped"):
        table.add_row(st, str(counts.get(st, 0)))
    console.print(table)
    conn.close()


@app.command()
def export(out: Optional[str] = typer.Option(None, "--out", help="CSV path (default stdout)")):
    """Export the full table as CSV."""
    conn = db.connect(service.DB_FILE); db.init_schema(conn)
    rows = db.all_rows(conn)
    cols = ["id", "company", "title", "location", "state", "remote_flag", "url",
            "posted_at", "source", "salary_min", "salary_max", "score",
            "status", "applied_date", "notes", "first_seen", "last_seen"]
    fh = open(out, "w", newline="") if out else sys.stdout
    w = csv.writer(fh); w.writerow(cols)
    for r in rows:
        w.writerow([r[c] for c in cols])
    if out:
        fh.close(); console.print(f"[green]exported[/] {len(rows)} rows -> {out}")
    conn.close()


@app.command()
def ui(port: int = typer.Option(8501, help="port to serve on")):
    """Launch the local Streamlit web UI on localhost:<port>."""
    import os
    import subprocess

    cred = os.path.expanduser("~/.streamlit/credentials.toml")
    if not os.path.exists(cred):
        os.makedirs(os.path.dirname(cred), exist_ok=True)
        with open(cred, "w") as fh:
            fh.write('[general]\nemail = ""\n')
    ui_path = os.path.join(os.path.dirname(__file__), "ui.py")
    console.print(f"[green]jobfeed UI[/] → http://localhost:{port}  (Ctrl+C to stop)")
    subprocess.run([sys.executable, "-m", "streamlit", "run", ui_path,
                    "--server.port", str(port), "--server.address", "localhost",
                    "--server.headless", "true", "--browser.gatherUsageStats", "false"])
