"""Load config.yaml + .env. Everything profession-specific — the search terms,
title filters, scoring — lives in config.yaml (generated by `jf init`), never
in Python."""
from __future__ import annotations

import os
import re
from functools import lru_cache
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import yaml

ROOT = Path(__file__).resolve().parent.parent


def load_env(path: Optional[Path] = None) -> Dict[str, str]:
    """Parse a simple KEY=VALUE .env into os.environ (without overriding the
    real environment)."""
    path = path or ROOT / ".env"
    parsed: Dict[str, str] = {}
    if path.exists():
        for line in path.read_text().splitlines():
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, val = line.split("=", 1)
            parsed[key.strip()] = val.strip()
    for key, val in parsed.items():
        os.environ.setdefault(key, val)
    return parsed


class Config:
    """Typed, regex-compiled view over config.yaml."""

    def __init__(self, data: dict):
        self.raw = data
        self.profession: str = data.get("profession", "")

        query = data.get("query", {})
        self.adzuna_what: str = query.get("adzuna_what") or self.profession
        self.remotive_category: str = query.get("remotive_category", "") or ""

        titles = data["titles"]
        self.titles_include = [re.compile(p) for p in titles.get("include", [])]
        self.titles_exclude = [re.compile(p) for p in titles.get("exclude", [])]

        loc = data.get("locations", {})
        self.accept_remote_us: bool = loc.get("accept_remote_us", True)
        self.states: List[str] = list(loc.get("states", []))
        self.city_hints: Dict[str, List[str]] = loc.get("city_hints", {})
        self.remote_hints: List[str] = loc.get("remote_hints", ["Remote", "Anywhere"])
        self.reject_hints: List[str] = loc.get("reject_hints", [])

        comp = data.get("compensation", {})
        self.comp_drop_below = comp.get("drop_below")
        self.comp_flag_below = comp.get("flag_below")

        sc = data.get("scoring", {})
        self.keyword_boosts: List[Tuple[re.Pattern, int]] = [
            (re.compile(p), pts) for p, pts in (sc.get("keyword_boosts") or {}).items()
        ]
        self.keyword_penalties: List[Tuple[re.Pattern, int]] = [
            (re.compile(p), pts) for p, pts in (sc.get("keyword_penalties") or {}).items()
        ]
        self.state_boosts: Dict[str, int] = sc.get("state_boosts", {})
        self.remote_boost: int = sc.get("remote_boost", 0)
        self.freshness: Dict[str, int] = sc.get("freshness", {})

        dg = data.get("digest", {})
        self.digest_top_n: int = dg.get("top_n", 25)
        self.digest_min_score: int = dg.get("min_score", 0)

        f = data.get("fetch", {})
        self.max_rps: float = float(f.get("max_requests_per_second", 8))
        self.timeout: float = float(f.get("timeout_seconds", 10))
        self.retries: int = int(f.get("retries", 1))

        s = data.get("sources", {})
        self.sources_enabled: Dict[str, bool] = {
            "adzuna": s.get("adzuna", True),
            "remotive": s.get("remotive", True),
            "remoteok": s.get("remoteok", True),
            "greenhouse": s.get("greenhouse", False),
            "ashby": s.get("ashby", False),
            "lever": s.get("lever", False),
        }


@lru_cache(maxsize=1)
def get_config(path: Optional[str] = None) -> Config:
    load_env()
    cfg_path = Path(path) if path else ROOT / "config.yaml"
    if not cfg_path.exists():
        raise FileNotFoundError(
            "config.yaml not found — run `jf init \"<your profession>\"` first."
        )
    with open(cfg_path) as fp:
        return Config(yaml.safe_load(fp))
